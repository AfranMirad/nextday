  static final Map<String, HabitDefinition> _byId = {
    for (final d in all) d.id: d,
  };

  static HabitDefinition? byId(String id) => _byId[id];

  static HabitDefinition require(String id) =>
      _byId[id] ??
      HabitDefinition(
        id: id,
        category: HabitCategory.lifestyleStart,
        kind: HabitKind.start,
        titleTr: id,
        titleEn: id,
        shortTr: id,
        shortEn: id,
        icon: Icons.flag_outlined,
        badgeColor: AppTheme.sage,
      );

  static List<HabitDefinition> byCategory(HabitCategory category) =>
      all.where((d) => d.category == category).toList(growable: false);

  static const List<HabitCategory> orderedCategories = HabitCategory.values;
