enum HabitKind { quit, start }

class HabitDefinition {
  const HabitDefinition({
    required this.id,
    required this.category,
    required this.kind,
    required this.titleTr,
    required this.titleEn,
    required this.shortTr,
    required this.shortEn,
    required this.icon,
    required this.badgeColor,
